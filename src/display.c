void draw(int x, int y){
	if(x >= SCREEN_WIDTH)  x = SCREEN_WIDTH - 1;
	if(x < 0)              x = 0;

	if(y >= SCREEN_HEIGHT) y = SCREEN_HEIGHT - 1;
	if(y < 0)              y = 0;
	
	// Since in Unix Terminal (0;0) is equal to (1;1) shift everything to +1
	x++;
	y++;
	printf("\033[%d;%dH*", x, y);
}

